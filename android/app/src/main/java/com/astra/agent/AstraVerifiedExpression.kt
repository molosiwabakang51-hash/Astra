package com.astra.agent

import java.math.BigDecimal
import java.util.Locale

/**
 * Small, completely offline exact arithmetic parser. Handles only an
 * owner-authored, FULL-MESSAGE "calculate/what is" expression, not a passage,
 * task command, finance decision, imported file or other model text.
 *
 * Supports +, -, *, /, parentheses and written operator names. Bounded
 * number size, token count, nesting and result precision defend against
 * resource exhaustion. Non-terminating divisions are not rounded and
 * cannot be certified as exact; those return null to the existing route.
 *
 * This improves tool correctness; it does NOT train or upgrade Qwen3.
 */
internal object AstraVerifiedExpression {
    private const val MAX_INPUT = 200
    private const val MAX_TOKENS = 39
    private const val MAX_OPERANDS = 15
    private const val MAX_LEVELS = 4

    private val command = Regex(
        """^(?:what is|what's|calculate|compute|work out|please calculate)\s+(.+)$""",
        RegexOption.IGNORE_CASE
    )
    private val answerOnlySuffix = Regex(
        """\s+(?:reply|answer)\s+only\s+with\s+(?:the\s+)?""" +
            """(?:number|result|answer)\s*[.!]?$""",
        RegexOption.IGNORE_CASE
    )
    private val numeric = Regex("""[0-9]{1,9}(?:\.[0-9]{1,4})?""")
    private val wordOperators = listOf(
        Regex("""\bmultiplied\s+by\b""", RegexOption.IGNORE_CASE) to "*",
        Regex("""\bdivided\s+by\b""", RegexOption.IGNORE_CASE) to "/",
        Regex("""\btimes\b""", RegexOption.IGNORE_CASE) to "*",
        Regex("""\bplus\b""", RegexOption.IGNORE_CASE) to "+",
        Regex("""\bminus\b""", RegexOption.IGNORE_CASE) to "-"
    )

    private class Invalid : RuntimeException()
    private class DivisionByZero : RuntimeException()
    private data class Outcome(
        val result: String,
        val steps: List<String>,
        val defined: Boolean
    )

    fun answer(raw: String): String? = solve(raw)?.result

    /** Verify the observed completed reply before showing the exact workings. */
    fun verifiedWorking(originalQuestion: String, previousAnswer: String): String? {
        val outcome = solve(originalQuestion) ?: return null
        if (!outcome.defined || outcome.result != previousAnswer.trim() ||
            outcome.steps.isEmpty()
        ) return null
        return "Verified local multi-step calculation:\n" +
            outcome.steps.joinToString("\n") +
            "\nFinal exact result: " + outcome.result +
            "\nThese steps are recomputed locally, not generated by the AI."
    }

    private fun solve(raw: String): Outcome? {
        if (raw.length !in 8..MAX_INPUT || raw.contains('\n') ||
            raw.contains('\r')
        ) return null
        val match = command.matchEntire(raw.trim()) ?: return null
        var expression = match.groupValues[1].trim()
            .replace(answerOnlySuffix, "").trim().trimEnd('?', '!', '.', ' ')
        for ((word, symbol) in wordOperators) {
            expression = expression.replace(word, " " + symbol + " ")
        }
        // User keyboards and copied mathematics commonly produce the
        // typographic operators ×, ÷ and U+2212 (minus). Normalize only
        // those exact arithmetic glyphs; never evaluate arbitrary Unicode
        // text, implicit multiplication or unsupported mathematical syntax.
        expression = expression.replace('×', '*')
            .replace('÷', '/')
            .replace('−', '-')
        if (expression.length > MAX_INPUT) return null
        val tokens = tokenize(expression) ?: return null
        // Simple two-number arithmetic remains with AstraVerifiedArithmetic.
        // This parser handles genuine multi-step or grouped requests only.
        val numbers = tokens.count { numeric.matches(it) }
        if (numbers > MAX_OPERANDS || numbers < 2 ||
            (numbers < 3 && "(" !in tokens)
        ) return null
        return try {
            Parser(tokens).evaluate()
        } catch (_: DivisionByZero) {
            Outcome("Division by zero is undefined.", emptyList(), false)
        } catch (_: Invalid) {
            null
        } catch (_: ArithmeticException) {
            null
        }
    }

    private fun tokenize(value: String): List<String>? {
        val result = mutableListOf<String>()
        var index = 0
        while (index < value.length) {
            val char = value[index]
            when {
                char.isWhitespace() -> index++
                char.isDigit() -> {
                    val match = numeric.find(value, index)
                        ?.takeIf { it.range.first == index } ?: return null
                    result.add(match.value)
                    index = match.range.last + 1
                }
                char in "+-*/()" -> {
                    result.add(char.toString())
                    index++
                }
                else -> return null
            }
            if (result.size > MAX_TOKENS) return null
        }
        return result.takeIf { it.isNotEmpty() }
    }

    private fun numberString(value: BigDecimal): String =
        value.stripTrailingZeros().toPlainString()

    private class Parser(private val tokens: List<String>) {
        private var at = 0
        private var operands = 0
        private val steps = mutableListOf<String>()

        fun evaluate(): Outcome {
            val result = sum(0)
            if (at != tokens.size || operands > MAX_OPERANDS ||
                steps.size > MAX_OPERANDS
            ) throw Invalid()
            return Outcome(numberString(result), steps.toList(), true)
        }

        private fun peek(): String? = tokens.getOrNull(at)
        private fun pop(): String = tokens.getOrNull(at++) ?: throw Invalid()

        private fun sum(depth: Int): BigDecimal {
            var left = product(depth)
            while (peek() == "+" || peek() == "-") {
                val op = pop()
                left = operation(left, op, product(depth))
            }
            return left
        }

        private fun product(depth: Int): BigDecimal {
            var left = atom(depth)
            while (peek() == "*" || peek() == "/") {
                val op = pop()
                left = operation(left, op, atom(depth))
            }
            return left
        }

        private fun atom(depth: Int): BigDecimal {
            if (depth > MAX_LEVELS) throw Invalid()
            return when (val token = pop()) {
                "+" -> atom(depth)
                "-" -> atom(depth).negate()
                "(" -> {
                    if (depth >= MAX_LEVELS) throw Invalid()
                    val inside = sum(depth + 1)
                    if (pop() != ")") throw Invalid()
                    inside
                }
                else -> {
                    if (!numeric.matches(token)) throw Invalid()
                    operands++
                    if (operands > MAX_OPERANDS) throw Invalid()
                    token.toBigDecimal()
                }
            }
        }

        private fun operation(
            left: BigDecimal, op: String, right: BigDecimal
        ): BigDecimal {
            val value = when (op) {
                "+" -> left.add(right)
                "-" -> left.subtract(right)
                "*" -> left.multiply(right)
                "/" -> {
                    if (right.signum() == 0) throw DivisionByZero()
                    try {
                        left.divide(right)
                    } catch (_: ArithmeticException) {
                        throw Invalid()
                    }
                }
                else -> throw Invalid()
            }
            if (value.precision() > 45 || value.scale() > 16 ||
                value.scale() < -16
            ) throw Invalid()
            val symbol = when (op) {
                "*" -> "×"
                "/" -> "÷"
                "-" -> "−"
                else -> "+"
            }
            steps.add(
                numberString(left) + " " + symbol + " " +
                    numberString(right) + " = " + numberString(value)
            )
            return value
        }
    }
}
